"""Astronomical prayer time calculation.

A line-by-line port of ``MuslimDataCalculator.kt`` from the Android app, which is itself a
port of ``Prayer.swift`` from the MuslimData iOS project. Only 252 of the 166,404 known
locations carry a fixed timetable; everywhere else both apps fall through to this, so any
divergence here shows up as the phone and the desktop disagreeing.

Nothing about it is idiomatic Python on purpose: the odd bits - a single refinement
iteration, seconds truncated rather than rounded, high-latitude adjustment applied
unconditionally - are faithful to the original and must stay that way.

``tests/test_calculator.py`` asserts the output against times generated by running the
Kotlin class itself, so a well-meaning "fix" here fails the suite.
"""

from __future__ import annotations

import math
from datetime import date as Date

# angle, maghrib-is-fixed, maghrib value, isha-is-fixed, isha value
METHOD_PARAMS: dict[str, tuple[float, float, float, float, float]] = {
    "MAKKAH": (18.5, 1.0, 0.0, 1.0, 90.0),
    "MWL": (18.0, 1.0, 0.0, 0.0, 17.0),
    "ISNA": (15.0, 1.0, 0.0, 0.0, 15.0),
    "KARACHI": (18.0, 1.0, 0.0, 0.0, 18.0),
    "EGYPT": (18.0, 1.0, 0.0, 0.0, 17.0),
    "JAFARI": (16.0, 0.0, 4.0, 0.0, 14.0),
    "TEHRAN": (17.7, 0.0, 4.5, 0.0, 14.0),
    "CUSTOM": (19.5, 1.0, 0.0, 0.0, 17.5),
}

#: Which method the phone picks when the user leaves it on automatic. Mirrors
#: PrayerManager.autoMethodForCountry.
_METHOD_BY_COUNTRY: dict[str, str] = {
    "SA": "MAKKAH",
    "AE": "MAKKAH",
    "QA": "MAKKAH",
    "KW": "MAKKAH",
    "BH": "MAKKAH",
    "EG": "EGYPT",
    "PK": "KARACHI",
    "IN": "KARACHI",
    "BD": "KARACHI",
    "AF": "KARACHI",
    "IR": "TEHRAN",
    "US": "ISNA",
    "CA": "ISNA",
}

HIGH_LAT_ANGLE_BASED = 3


def method_for_country(country_code: str) -> str:
    return _METHOD_BY_COUNTRY.get((country_code or "").upper(), "MWL")


def _fix_angle(a: float) -> float:
    angle = a - 360.0 * math.floor(a / 360.0)
    return angle + 360.0 if angle < 0 else angle


def _fix_hour(a: float) -> float:
    hour = a - 24.0 * math.floor(a / 24.0)
    return hour + 24.0 if hour < 0 else hour


def _sin(d: float) -> float:
    return math.sin(math.radians(d))


def _cos(d: float) -> float:
    return math.cos(math.radians(d))


def _tan(d: float) -> float:
    return math.tan(math.radians(d))


def _arcsin(x: float) -> float:
    return math.degrees(math.asin(max(-1.0, min(1.0, x))))


def _arccos(x: float) -> float:
    return math.degrees(math.acos(max(-1.0, min(1.0, x))))


def _arctan2(y: float, x: float) -> float:
    return math.degrees(math.atan2(y, x))


def _arccot(x: float) -> float:
    return math.degrees(math.atan2(1.0, x))


def _julian_date(year: int, month: int, day: int) -> float:
    if month <= 2:
        year -= 1
        month += 12
    a = math.floor(year / 100.0)
    b = 2 - a + math.floor(a / 4.0)
    return (
        math.floor(365.25 * (year + 4716))
        + math.floor(30.6001 * (month + 1))
        + day
        + b
        - 1524.5
    )


class PrayerCalculator:
    def __init__(
        self,
        method: str = "MAKKAH",
        asr_juristic: int = 0,
        dhuhr_minutes: int = 0,
        adjust_high_lats: int = HIGH_LAT_ANGLE_BASED,
    ) -> None:
        self.method = method
        #: 0 for Shafi'i, 1 for Hanafi.
        self.asr_juristic = asr_juristic
        self.dhuhr_minutes = dhuhr_minutes
        self.adjust_high_lats = adjust_high_lats

        self.lat = 0.0
        self.lng = 0.0
        self.time_zone = 0.0
        self.j_date = 0.0

    # --- public ---------------------------------------------------------------------

    def prayer_times(
        self, day: Date, latitude: float, longitude: float, timezone_hours: float
    ) -> dict[str, str]:
        self.lat = latitude
        self.lng = longitude
        self.time_zone = timezone_hours
        self.j_date = _julian_date(day.year, day.month, day.day) - longitude / (
            15.0 * 24.0
        )
        return self._compute_day_times()

    # --- internals ------------------------------------------------------------------

    @property
    def _params(self) -> tuple[float, float, float, float, float]:
        return METHOD_PARAMS[self.method]

    def _sun_position(self, jd: float) -> tuple[float, float]:
        d_days = jd - 2451545.0
        g = _fix_angle(357.529 + 0.98560028 * d_days)
        q = _fix_angle(280.459 + 0.98564736 * d_days)
        lon = _fix_angle(q + 1.915 * _sin(g) + 0.020 * _sin(2 * g))

        e = 23.439 - (0.00000036 * d_days)
        declination = _arcsin(_sin(e) * _sin(lon))
        right_ascension = _fix_hour(_arctan2(_cos(e) * _sin(lon), _cos(lon)) / 15.0)
        return declination, q / 15.0 - right_ascension

    def _compute_mid_day(self, t: float) -> float:
        return _fix_hour(12 - self._sun_position(self.j_date + t)[1])

    def _compute_time(self, g: float, t: float) -> float:
        declination = self._sun_position(self.j_date + t)[0]
        noon = self._compute_mid_day(t)
        v = (
            1.0
            / 15.0
            * _arccos(
                (-_sin(g) - _sin(declination) * _sin(self.lat))
                / (_cos(declination) * _cos(self.lat))
            )
        )
        return noon + (-v if g > 90 else v)

    def _compute_asr(self, step: float, t: float) -> float:
        declination = self._sun_position(self.j_date + t)[0]
        return self._compute_time(
            -_arccot(step + _tan(abs(self.lat - declination))), t
        )

    def _compute_times(self, times: list[float]) -> list[float]:
        t = [value / 24.0 for value in times]
        parm = self._params
        return [
            self._compute_time(180 - parm[0], t[0]),  # fajr
            self._compute_time(180 - 0.833, t[1]),  # sunrise
            self._compute_mid_day(t[2]),  # dhuhr
            self._compute_asr(1.0 + self.asr_juristic, t[3]),  # asr
            self._compute_time(0.833, t[4]),  # sunset
            self._compute_time(parm[2], t[5]),  # maghrib
            self._compute_time(parm[4], t[6]),  # isha
        ]

    def _compute_day_times(self) -> dict[str, str]:
        # One refinement pass, matching the Swift original. Two would shift some times by
        # a second and break agreement with the phone.
        times = self._compute_times([5.0, 6.0, 12.0, 13.0, 18.0, 18.0, 18.0])
        times = self._adjust_times(times)

        keys = ("Fajr", "Sunrise", "Dhuhr", "Asr", "Sunset", "Maghrib", "Isha")
        return {key: _float_to_time24(value) for key, value in zip(keys, times)}

    def _adjust_times(self, times: list[float]) -> list[float]:
        adjusted = [value + self.time_zone - self.lng / 15.0 for value in times]
        parm = self._params

        adjusted[2] += self.dhuhr_minutes / 60.0

        if parm[1] == 1.0:  # maghrib is a fixed interval after sunset
            adjusted[5] = adjusted[4] + parm[2] / 60.0
        if parm[3] == 1.0:  # isha is a fixed interval after maghrib
            adjusted[6] = adjusted[5] + parm[4] / 60.0

        if self.adjust_high_lats != 0:
            adjusted = self._adjust_high_lat_times(adjusted)
        return adjusted

    def _adjust_high_lat_times(self, times: list[float]) -> list[float]:
        night_time = _fix_hour(times[1] - times[4])  # sunset to sunrise
        parm = self._params

        fajr_diff = self._night_portion(parm[0]) * night_time
        if math.isnan(times[0]) or _fix_hour(times[1] - times[0]) > fajr_diff:
            times[0] = times[1] - fajr_diff

        isha_angle = parm[4] if parm[3] == 0.0 else 18.0
        isha_diff = self._night_portion(isha_angle) * night_time
        if math.isnan(times[6]) or _fix_hour(times[6] - times[4]) > isha_diff:
            times[6] = times[4] + isha_diff

        maghrib_angle = parm[2] if parm[1] == 0.0 else 4.0
        maghrib_diff = self._night_portion(maghrib_angle) * night_time
        if math.isnan(times[5]) or _fix_hour(times[5] - times[4]) > maghrib_diff:
            times[5] = times[4] + maghrib_diff

        return times

    def _night_portion(self, angle: float) -> float:
        if self.adjust_high_lats == 3:
            return angle / 60.0
        if self.adjust_high_lats == 1:
            return 0.5
        if self.adjust_high_lats == 2:
            return 0.14286
        return 0.0


def _float_to_time24(value: float) -> str:
    """Decimal hours as ``HH:MM:SS``, seconds truncated rather than rounded."""
    if math.isnan(value):
        return "00:00:00"
    total_seconds = int(math.floor(_fix_hour(value) * 3600.0))
    return (
        f"{total_seconds // 3600:02d}:"
        f"{(total_seconds % 3600) // 60:02d}:"
        f"{total_seconds % 60:02d}"
    )
